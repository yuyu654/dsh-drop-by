// private.js —— 「这条不许拿出去用」的自我标记。
//
// 我在 self.md / 记忆里给自己写下的判断，有时会带一句「这条不给 XX 看」「太贴」「自己消化」。
// 那种条目是内部判断，**绝不能拿去当素材或搭话的种子**——方向是「我不给对方看」，
// 不是「对方瞒着我」。
//
// 正则不写死具体名字：`不给 XX 看` 里的 XX 是谁都算，换个人用这个插件也照样过滤。
export const PRIVATE_MARK = /不给[^\s，。；、！？]{1,8}看|不能给[^\s，。；、！？]{1,8}看|自己消化|不直接发|太贴|别[让给][^\s，。；、！？]{0,8}看到|内部/;

/** 一段文字是不是我自己标了「别拿出去」。 */
export function isPrivate(text) {
  return PRIVATE_MARK.test(String(text || ''));
}